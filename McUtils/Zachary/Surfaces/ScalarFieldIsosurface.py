"""Isosurfaces that retain the field needed to regenerate their geometry."""
from pathlib import Path
import numpy as np

from ..ScalarFields import ScalarField
from ...Data import UnitsData
from .MarchingCubesSurface import CORNER_OFFSETS, EDGE_CORNERS, TRI_TABLE

__all__ = ["ScalarFieldIsosurface"]


class ScalarFieldIsosurface:
    """A level set of a sampled field, rather than a detached triangle mesh.

    ``get_mesh()`` generates the current geometry. X3D plots retain this object
    so the standard ``animate_frames`` path can regenerate geometry from the
    interpolated fields at every fraction, including topology changes.
    """

    def __init__(self, scalar_field, isovalue, *, interpolation="linear"):
        if not isinstance(scalar_field, ScalarField):
            raise TypeError("scalar_field must be a ScalarField")
        if scalar_field.values.ndim != 3:
            raise ValueError("ScalarFieldIsosurface requires a three-dimensional field")
        isovalue = float(isovalue)
        if not np.isfinite(isovalue):
            raise ValueError("isovalue must be finite")
        if interpolation != "linear":
            raise ValueError("supported scalar-field interpolation method: 'linear'")
        self.scalar_field = scalar_field
        self.isovalue = float(isovalue)
        self.interpolation = interpolation

    @property
    def field(self):
        return self.scalar_field

    def interpolate(self, other, fraction):
        if not isinstance(other, ScalarFieldIsosurface) or self.interpolation != other.interpolation:
            raise TypeError("interpolation requires compatible ScalarFieldIsosurface objects")
        fraction = float(fraction)
        field = self.field.interpolate(other.field, fraction, method=self.interpolation)
        return ScalarFieldIsosurface(field, (1 - fraction) * self.isovalue + fraction * other.isovalue,
                                    interpolation=self.interpolation)

    def get_mesh(self):
        # Geometry normals are generated by the plotting/animation backend.
        return self.field.get_isosurface(self.isovalue, return_normals=False)

    def coordinate_scale(self, distance_units=None):
        source = self.field.coordinate_units
        if source is None:
            if distance_units is not None:
                raise ValueError("field coordinate units are unspecified")
            return 1.
        if distance_units is None:
            distance_units = "Angstroms"
        return UnitsData.convert(source, distance_units)

    def plot(self, figure=None, *, backend="x3d", distance_units=None, color="blue",
             transparency=.8, line_color=None, **styles):
        from ...Plots import Graphics3D
        if figure is None:
            figure = Graphics3D(backend=backend)
        scale = self.coordinate_scale(distance_units)
        axes = figure.axes
        if line_color is not None:
            raise ValueError("field-backed isosurfaces currently support filled surfaces; line_color must be None")
        if hasattr(axes, 'draw_isosurface'):
            axes.draw_isosurface(self, coordinate_scale=scale, color=color,
                                transparency=transparency, **styles)
        else:
            mesh = self.get_mesh()
            mesh.plot_triangle_mesh(mesh.verts * scale, mesh.inds, figure=figure, color=color,
                                    transparency=transparency, **styles)
        return figure

    @staticmethod
    def javascript_source():
        return (Path(__file__).with_name('resources') / 'ScalarFieldIsosurface.js').read_text()

    @staticmethod
    def marching_cubes_tables():
        # The browser consumes the existing extractor's tables, not another contouring scheme.
        return dict(corners=np.asarray(CORNER_OFFSETS).tolist(), edges=np.asarray(EDGE_CORNERS).tolist(),
                    triangles=TRI_TABLE)
